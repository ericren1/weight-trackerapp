PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  current_phase TEXT NOT NULL DEFAULT 'Cut'
    CHECK (current_phase IN ('Cut', 'Maintain', 'Gain')),
  current_phase_started_on TEXT NOT NULL DEFAULT '2026-10-05',
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT OR IGNORE INTO settings (id, current_phase, current_phase_started_on)
VALUES (1, 'Cut', '2026-10-05');

CREATE TABLE IF NOT EXISTS weight_entries (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  date TEXT NOT NULL UNIQUE,
  weight REAL NOT NULL CHECK (weight > 0 AND weight < 1000),
  phase TEXT NULL CHECK (phase IS NULL OR phase IN ('Cut', 'Maintain', 'Gain')),
  notes TEXT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_weight_entries_date
ON weight_entries(date);

